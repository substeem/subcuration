/**
 * Flags posts that are tagged #nsfw, categorized as nsfw, or contain is_nsfw metadata.
 * Completely banned from radar feeds, rescue queues, opportunities, and reports.
 */
export function isNsfwPost(post: {
  category?: string;
  tags?: string[];
  json_metadata?: unknown;
}): boolean {
  const cat = (post.category || '').toLowerCase().trim();
  if (cat === 'nsfw' || cat.startsWith('nsfw-') || cat.endsWith('-nsfw')) return true;

  if (Array.isArray(post.tags)) {
    if (post.tags.some((t) => typeof t === 'string' && t.toLowerCase().trim() === 'nsfw')) {
      return true;
    }
  }

  if (post.json_metadata) {
    try {
      const meta =
        typeof post.json_metadata === 'string'
          ? JSON.parse(post.json_metadata)
          : post.json_metadata;
      if (meta && typeof meta === 'object') {
        if ((meta as any).is_nsfw === true || (meta as any).nsfw === true) return true;
        if (Array.isArray((meta as any).tags)) {
          if (
            (meta as any).tags.some(
              (t: any) => typeof t === 'string' && t.toLowerCase().trim() === 'nsfw'
            )
          ) {
            return true;
          }
        }
      }
    } catch {}
  }

  return false;
}

/**
 * Flags automated spam bots, coin-doubler promotions, betting tables, and explicitly AI-generated text.
 */
export function isLowQualityOrBotPost(post: {
  author: string;
  title?: string;
  category?: string;
  body?: string;
  tags?: string[];
  json_metadata?: unknown;
}): boolean {
  if (isNsfwPost(post)) return true;

  const authorNorm = (post.author || '').toLowerCase().trim();
  if (KNOWN_BOT_ACCOUNTS.has(authorNorm)) return true;

  const haystack = [
    post.title || '',
    post.category || '',
    post.body || '',
    ...(Array.isArray(post.tags) ? post.tags : []),
  ]
    .join(' ')
    .toLowerCase();

  if (SPAM_OR_BOT_PATTERNS.some((p) => haystack.includes(p))) return true;
  if (/(?:profit\s+within|steem.*profit|profit.*steem|\d+%\s*profit)/i.test(haystack)) return true;
  if (AI_DISCLOSURE_PHRASES.some((p) => haystack.includes(p))) return true;

  return false;
}

/**
 * Canonical Diary Game detector used across radar filters, banners, and POD reports.
 * Checks category, title, and all post tags.
 */
export function isDiaryPost(post: {
  category?: string;
  title?: string;
  tags?: string[];
}): boolean {
  const haystack = [
    post.category || '',
    post.title || '',
    ...(Array.isArray(post.tags) ? post.tags : []),
  ]
    .join(' ')
    .toLowerCase();

  return DIARY_KEYWORDS.some((kw) => haystack.includes(kw));
}

